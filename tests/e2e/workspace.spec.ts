import { readFile } from 'node:fs/promises'
import path from 'node:path'
import { expect, test } from '@playwright/test'
import { addSite, command, launchDesktop, remoteClick, state, stopAll, testSite } from './helpers'

test('独立会话、实时画面、中文输入、弹窗、Cookie 及重启恢复', async () => {
  const website = await testSite()
  let desktop: Awaited<ReturnType<typeof launchDesktop>> | undefined
  try {
    desktop = await launchDesktop()
    const { page, application, dataDir } = desktop
    await page.screenshot({ path: 'test-results/workspace-empty.png' })
    await page.getByRole('button', { name: '添加第一个网站' }).click()
    await page.getByLabel('名称', { exact: true }).fill('测试账号 A')
    await page.getByLabel('网站地址', { exact: true }).fill(`${website.origin}/?client=a`)
    await page.getByRole('dialog').getByRole('button', { name: '添加网站' }).click()
    await expect(page.getByRole('dialog')).toBeHidden()
    const a = (await state(page)).config.sites[0]
    const b = await addSite(page, '测试账号 B', `${website.origin}/?client=b`)
    await Promise.all([command(page, { type: 'browser.start', siteId: a.id }), command(page, { type: 'browser.start', siteId: b.id })])
    await expect.poll(() => website.reports.size).toBe(2)
    expect((await state(page)).runtimes.every((runtime) => runtime.status === 'running')).toBe(true)
    await page.getByRole('button', { name: '放大 测试账号 A', exact: true }).click()
    await expect(page.getByRole('button', { name: '返回网格' })).toBeVisible()
    await remoteClick(page, 150, 182)
    await page.keyboard.insertText('中文输入测试')
    await expect.poll(() => website.reports.get('a')?.text).toBe('中文输入测试')
    await page.keyboard.press('Meta+A')
    await page.keyboard.press('Meta+C')
    await expect.poll(() => application.evaluate(async ({ clipboard }) => clipboard.readText())).toBe('中文输入测试')
    await page.keyboard.press('ArrowRight')
    await page.keyboard.press('Meta+V')
    await expect.poll(() => website.reports.get('a')?.text).toBe('中文输入测试中文输入测试')
    await remoteClick(page, 100, 260)
    await expect.poll(() => website.reports.get('a')?.indexed).toBe('a')
    expect(website.reports.get('b')?.cookie).toBe('')
    expect(website.reports.get('b')?.local).toBeNull()
    await command(page, { type: 'cookie.capture', siteId: a.id })
    const encrypted = await readFile(path.join(dataDir, 'cookie-vault', `${a.id}.enc`))
    expect(encrypted.includes(Buffer.from('"login"'))).toBe(false)
    await page.screenshot({ path: 'test-results/workspace-focus.png' })
    await remoteClick(page, 280, 260)
    await expect.poll(async () => (await state(page)).runtimes.find((runtime) => runtime.siteId === a.id)?.tabs.length).toBe(2)
    await expect(page.locator('.tab-title').filter({ hasText: '授权窗口' })).toBeVisible()
    await remoteClick(page, 120, 222)
    await expect.poll(() => website.reports.get('a')?.callback).toBe(true)
    await expect.poll(async () => (await state(page)).runtimes.find((runtime) => runtime.siteId === a.id)?.tabs.length).toBe(1)
    await remoteClick(page, 440, 260)
    await expect(page.getByRole('dialog').getByText('测试对话框', { exact: true })).toBeVisible()
    await page.getByRole('dialog').getByRole('button', { name: '确 定' }).click()
    await expect.poll(() => website.reports.get('a')?.dialog).toBe(true)
    await expect(page.getByRole('dialog')).toBeHidden()
    await remoteClick(page, 700, 205)
    await page.keyboard.insertText('跨域中文')
    await expect.poll(() => website.reports.get('a')?.frameText).toBe('跨域中文')
    await page.getByRole('button', { name: 'Cookie 管理', exact: true }).click()
    await page.getByRole('tab', { name: 'Cookie 字符串' }).click()
    await page.getByPlaceholder('session=…; preference=…').fill('manual=header-value')
    await page.getByRole('button', { name: '预览并合并到表格' }).click()
    await page.getByRole('button', { name: '保存并应用' }).click()
    await expect(page.getByRole('dialog')).toBeHidden()
    await expect.poll(() => website.reports.get('a')?.cookie).toContain('manual=header-value')
    await command(page, { type: 'browser.stop', siteId: a.id })
    website.reports.delete('a')
    await command(page, { type: 'browser.start', siteId: a.id })
    await expect.poll(() => website.reports.get('a')?.indexed).toBe('a')
    expect(website.reports.get('a')?.local).toBe('a')
    expect(website.reports.get('a')?.cookie).toContain('login=a')
    await page.getByRole('button', { name: '返回网格' }).click()
    await page.screenshot({ path: 'test-results/workspace-grid.png' })
    await stopAll(application, page)
    desktop = await launchDesktop(dataDir)
    expect((await state(desktop.page)).config.sites).toHaveLength(2)
    expect((await state(desktop.page)).runtimes).toHaveLength(0)
  } finally {
    if (desktop) await stopAll(desktop.application, desktop.page).catch(() => undefined)
    await website.close()
  }
})
